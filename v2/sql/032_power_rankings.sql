-- Power rankings of clubs and players: the method of docs/METHODE_CLASSEMENT_BALLON_D_OR.md
-- (main), computed by vega_v2/power.py.
-- - Club power ranking: the Elo strength of § 3, updated match after match.
-- - Player power ranking: the role-relative score B of §§ 4–8, built from each match's
--   contribution C (the role played, the minutes, the opponent's strength before the match).
-- The method leaves points open (its § 12): each choice is a named setting of power.py,
-- kept with every run in agg.power_runs.

-- The role of § 4 from a line-up slot. Slots 0–3 only name a line (substitutes): the
-- player's role is then his most played one, else the line's default (power.py).
CREATE FUNCTION core.power_role(position_id integer)
RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT CASE
    WHEN position_id IN (0, 11) THEN 'goalkeeper'
    WHEN position_id IN (51, 59) THEN 'full_back'
    WHEN position_id BETWEEN 30 AND 39 THEN CASE WHEN position_id % 10 IN (1, 2, 8, 9) THEN 'full_back' ELSE 'centre_back' END
    WHEN position_id BETWEEN 50 AND 69 THEN 'defensive_midfielder'
    WHEN position_id BETWEEN 70 AND 79 THEN 'central_midfielder'
    WHEN position_id BETWEEN 80 AND 89 THEN 'winger'
    WHEN position_id BETWEEN 90 AND 119 THEN CASE WHEN position_id % 10 IN (1, 2, 8, 9) THEN 'winger' ELSE 'centre_forward' END
  END
$$;

CREATE TABLE agg.power_runs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('elo', 'players')),
  season_id smallint REFERENCES core.seasons,
  method_version text NOT NULL,
  -- The settings of the run, one typed column each.
  elo_initial real, elo_k real, elo_home_advantage real,
  regularisation_minutes real, eligibility_minutes real, total_weight real, rate_weight real,
  min_reference_matches integer, matches integer, players integer,
  status text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'published', 'superseded')),
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz
);

-- § 3: each team's strength before and after each match, in match order.
CREATE TABLE agg.team_elo (
  match_id integer NOT NULL,
  team_id integer NOT NULL REFERENCES core.teams,
  season_id smallint NOT NULL,
  kickoff_at timestamptz,
  elo_before real NOT NULL,
  elo_after real NOT NULL,
  expected real NOT NULL,
  result real NOT NULL CHECK (result IN (0, 0.5, 1)),
  run_id integer NOT NULL REFERENCES agg.power_runs,
  PRIMARY KEY (match_id, team_id)
);
CREATE INDEX team_elo_team ON agg.team_elo(team_id, kickoff_at);

-- The club power ranking of a season: the strength after the club's last match of it.
CREATE TABLE agg.team_power (
  season_id smallint NOT NULL REFERENCES core.seasons,
  team_id integer NOT NULL REFERENCES core.teams,
  scope text NOT NULL CHECK (scope IN ('clubs', 'nations')),
  elo real NOT NULL,
  elo_change real NOT NULL,
  matches integer NOT NULL,
  rank integer NOT NULL,
  last_match_at timestamptz,
  run_id integer NOT NULL REFERENCES agg.power_runs,
  PRIMARY KEY (season_id, team_id)
);

-- §§ 5–6: one player's contribution in one match, by block, and in all (C).
CREATE TABLE agg.player_power_matches (
  season_id smallint NOT NULL,
  match_id integer NOT NULL,
  player_id integer NOT NULL REFERENCES core.players,
  team_id integer REFERENCES core.teams,
  role text NOT NULL,
  minutes smallint NOT NULL,
  opponent_elo real,
  finishing real, creation real, progression real, defence real, retention real,
  shot_stopping real, aerial real, depth real, distribution real,
  contribution real,
  run_id integer NOT NULL REFERENCES agg.power_runs,
  PRIMARY KEY (season_id, match_id, player_id)
);

-- § 8: the season's player power ranking (B), within the player's main role.
CREATE TABLE agg.player_power (
  season_id smallint NOT NULL REFERENCES core.seasons,
  player_id integer NOT NULL REFERENCES core.players,
  role text NOT NULL,
  team_id integer REFERENCES core.teams,
  matches integer NOT NULL,
  minutes integer NOT NULL,
  total real NOT NULL,           -- T
  rate real NOT NULL,            -- R*, per 90 regularised
  eligible boolean NOT NULL,
  total_percentile real,
  rate_percentile real,
  score real,                    -- B
  rank integer,
  role_rank integer,
  run_id integer NOT NULL REFERENCES agg.power_runs,
  PRIMARY KEY (season_id, player_id)
);
CREATE INDEX player_power_rank ON agg.player_power(season_id, rank);

-- Reads (GET /api/rankings/power).
CREATE VIEW api.power_clubs AS
SELECT se.label AS season, p.scope, p.rank, api.public_id('team', p.team_id) AS team_id, t.name, cr.source_url AS image_url,
  t.country_code AS country, p.elo::numeric::float8 AS elo, p.elo_change::numeric::float8 AS elo_change, p.matches,
  p.last_match_at, r.finished_at AS computed_at, r.method_version
FROM agg.team_power p
JOIN core.seasons se ON se.id = p.season_id
JOIN core.teams t ON t.id = p.team_id
LEFT JOIN core.assets cr ON cr.id = t.crest_asset_id
JOIN agg.power_runs r ON r.id = p.run_id;

CREATE VIEW api.power_players AS
SELECT se.label AS season, p.rank, p.role_rank, p.role, api.public_id('player', p.player_id) AS player_id, pl.name,
  ph.source_url AS image_url, api.public_id('team', p.team_id) AS team_id, t.name AS team, cr.source_url AS team_image_url,
  p.matches, p.minutes, p.total::numeric::float8 AS total, p.rate::numeric::float8 AS rate,
  p.total_percentile::numeric::float8 AS total_percentile, p.rate_percentile::numeric::float8 AS rate_percentile,
  p.score::numeric::float8 AS score, r.finished_at AS computed_at, r.method_version
FROM agg.player_power p
JOIN core.seasons se ON se.id = p.season_id
JOIN core.players pl ON pl.id = p.player_id
LEFT JOIN core.assets ph ON ph.id = pl.photo_asset_id
LEFT JOIN core.teams t ON t.id = p.team_id
LEFT JOIN core.assets cr ON cr.id = t.crest_asset_id
JOIN agg.power_runs r ON r.id = p.run_id
WHERE p.eligible;
