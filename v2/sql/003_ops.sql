CREATE TABLE ops.match_watch(
  match_id integer PRIMARY KEY REFERENCES core.matches,
  next_check_at timestamptz,
  checks smallint NOT NULL DEFAULT 0,
  state ops.watch_state NOT NULL DEFAULT 'scheduled',
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX match_watch_pending ON ops.match_watch(next_check_at)
WHERE state<>'corrected';-- Exactly one typed target: date calendar, competition-season calendar, or entity.

CREATE TABLE ops.fetch_jobs(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lane ops.fetch_lane NOT NULL,
  family ops.fetch_family NOT NULL,
  entity_type core.entity_type,
  entity_id integer,
  target_date date,
  competition_season_id integer REFERENCES core.competition_seasons,
  global_key text CHECK(global_key IS NULL OR global_key='catalogue'),
  run_after timestamptz NOT NULL DEFAULT now(),
  priority smallint NOT NULL DEFAULT 0,
  attempts smallint NOT NULL DEFAULT 0,
  state ops.job_state NOT NULL DEFAULT 'pending',
  lease_until timestamptz,
  lease_token uuid,
  last_http smallint,
  last_error_code text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((CASE WHEN target_date IS NOT NULL THEN 1 ELSE 0 END)+(CASE WHEN competition_season_id IS NOT NULL THEN 1 ELSE 0 END)+(CASE WHEN entity_id IS NOT NULL AND entity_type IS NOT NULL THEN 1 ELSE 0 END)+(CASE WHEN global_key IS NOT NULL THEN 1 ELSE 0 END)=1),
  CHECK ((entity_id IS NULL)=(entity_type IS NULL)),
  CHECK ((state='leased' AND lease_until IS NOT NULL AND lease_token IS NOT NULL) OR (state<>'leased' AND lease_until IS NULL AND lease_token IS NULL)),
  CHECK (((family='calendar' AND target_date IS NOT NULL) OR (family='league_matches' AND competition_season_id IS NOT NULL) OR (family='league' AND (global_key='catalogue' OR entity_type='competition')) OR (family='team' AND entity_type='team') OR (family='player' AND entity_type='player') OR (family IN ('summary', 'shots', 'events', 'lineups', 'momentum', 'team_stats', 'player_stats', 'player_halves', 'advanced', 'advanced_players', 'network', 'heatmaps', 'h2h') AND entity_type='match')) IS TRUE)
);

CREATE UNIQUE INDEX fetch_jobs_active_target ON ops.fetch_jobs(family, entity_type, entity_id, target_date, competition_season_id, global_key) NULLS NOT DISTINCT
WHERE state<>'done';

CREATE INDEX fetch_jobs_pending ON ops.fetch_jobs(lane, run_after, priority DESC)
WHERE state='pending';

CREATE TABLE ops.fetch_log(
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  job_id bigint,
  family ops.fetch_family,
  entity_type core.entity_type,
  entity_id integer,
  target_date date,
  competition_season_id integer,
  global_key text,
  http_status smallint,
  error_code text,
  request_id text,
  duration_ms integer,
  fetched_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(fetched_at, id)
) PARTITION BY RANGE(fetched_at );

CREATE TABLE ops.unknown_fields(
  family ops.fetch_family,
  field_path text,
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  occurrences integer NOT NULL DEFAULT 1,
  PRIMARY KEY(family, field_path)
);

CREATE TABLE ops.parse_failures(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  family ops.fetch_family,
  entity_type core.entity_type,
  entity_id integer,
  target_date date,
  competition_season_id integer,
  global_key text,
  error_code text,
  message text,
  at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE ops.dirty_scopes(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope_kind ops.scope_kind NOT NULL,
  player_id integer REFERENCES core.players,
  team_id integer REFERENCES core.teams,
  competition_season_id integer REFERENCES core.competition_seasons,
  cohort_id integer REFERENCES agg.cohorts,
  queued_at timestamptz NOT NULL DEFAULT now(),
  revision bigint NOT NULL DEFAULT 1,
  UNIQUE NULLS NOT DISTINCT(scope_kind, player_id, team_id, competition_season_id, cohort_id),
  CHECK ((scope_kind='player_season' AND player_id IS NOT NULL AND team_id IS NOT NULL AND competition_season_id IS NOT NULL AND cohort_id IS NULL) OR (scope_kind='team_season' AND player_id IS NULL AND team_id IS NOT NULL AND competition_season_id IS NOT NULL AND cohort_id IS NULL) OR (scope_kind='competition_season' AND player_id IS NULL AND team_id IS NULL AND competition_season_id IS NOT NULL AND cohort_id IS NULL) OR (scope_kind='cohort' AND player_id IS NULL AND team_id IS NULL AND competition_season_id IS NULL AND cohort_id IS NOT NULL))
);

CREATE TABLE ops.resource_versions(
  resource_kind ops.resource_kind,
  resource_id integer,
  version bigint NOT NULL DEFAULT 1,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(resource_kind, resource_id)
);

CREATE TABLE ops.schema_migrations(
  version text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now(),
  checksum bytea NOT NULL
);-- Successful payload fingerprints and attempt state; no response bodies are retained.

CREATE TABLE ops.family_state (
  match_id integer NOT NULL REFERENCES core.matches(id) ON DELETE CASCADE,
  family ops.fetch_family NOT NULL CHECK(family IN ('summary', 'shots', 'events', 'lineups', 'momentum', 'team_stats', 'player_stats', 'player_halves', 'advanced', 'advanced_players', 'network', 'heatmaps', 'h2h')),
  fingerprint bytea CHECK(fingerprint IS NULL OR octet_length(fingerprint)=32),
  status core.coverage_status NOT NULL DEFAULT 'pending',
  last_success_at timestamptz,
  last_attempt_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(match_id, family)
);
