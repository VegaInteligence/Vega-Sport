def _columns(cols):
    return "".join(f",\n  {name} {kind}" for name, kind in cols)


def _literal(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    return "'" + str(value).replace("'", "''") + "'"


def definitions_sql():
    """One agg.metric_definitions row per catalog metric and ratio, with its rule."""
    rows = []
    for entity, metrics, ratios in (
        ("player", PLAYER_METRICS, PLAYER_RATIOS),
        ("team", TEAM_METRICS, TEAM_RATIOS),
    ):
        for m in metrics:
            family = "advanced" if m.key.startswith("adv_") else "base"
            per90 = entity == "player" and m.rule == "sum"
            rows.append((entity, m.key, family, m.rule, None, None, m.weight, m.key, per90))
        for r in ratios:
            family = "advanced" if r.key.startswith("adv_") or r.key == "ppda" else "base"
            rows.append((entity, r.key, family, "ratio", r.numerator, r.denominator, None, r.key, False))
    values = ",\n  ".join(
        "(" + ", ".join(_literal(v) for v in row) + ")" for row in rows
    )
    return (
        "\nINSERT INTO agg.metric_definitions(entity_type, key, source_family, aggregation, numerator_key, "
        "denominator_key, weight_key, coverage_group, per90) VALUES\n  " + values + ";\n"
    )


