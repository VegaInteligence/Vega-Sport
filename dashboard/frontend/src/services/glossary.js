const SUFFIXES = [
  [" / match", " En moyenne par match."],
  [" / 90 min", " Par 90 minutes jouées."],
  [" /90", " Par 90 minutes jouées."],
];

const norm = (label) =>
  String(label || "")
    .normalize("NFC")
    .replace(/[’`]/g, "'")
    .replace(/\s+/g, " ")
    .replace(/\s*:\s*$/, "")
    .trim()
    .toLowerCase();

/** The sentence for a value's name, or null when the glossary does not hold it. */
export function explain(label) {
  const key = norm(label);
  if (!key) return null;
  if (TERMS[key]) return TERMS[key];
  for (const [suffix, tail] of SUFFIXES) {
    if (key.endsWith(suffix)) {
      const base = TERMS[key.slice(0, -suffix.length).trim()];
      if (base) return /[.!?]$/.test(base) ? `${base}${tail}` : `${base}.${tail}`;
    }
  }
  return null;
}

export const glossaryTerms = () => Object.keys(TERMS);
