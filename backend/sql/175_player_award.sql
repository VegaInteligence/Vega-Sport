-- moved. No column names a match.
SET LOCAL lock_timeout = '3s';

-- One run per award year and computation: the version, the settings (the value tables, the weights, the caps) and
-- the means and spreads it placed the year on. reference_season: the finished year those spreads are of (the year
-- itself once it is over: kept for the years after); NULL: the year's own, kept for no other year. failed: a ranking
-- run whose race failed, kept without players; the race published before stays published and served.
CREATE TABLE agg.award_runs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id smallint NOT NULL REFERENCES core.seasons,
  version text NOT NULL,
  status text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'published', 'superseded', 'failed')),
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  level_run_id integer REFERENCES agg.level_runs ON DELETE SET NULL,
  reference_season smallint,
  players integer,
  settings jsonb NOT NULL,
  spreads jsonb
);
CREATE UNIQUE INDEX award_runs_published ON agg.award_runs(season_id) WHERE status = 'published';

-- A men's player's parts, their z, his level A and score, his rank in the race or the first reason he is out of it.
-- individual and level in Elo points; collective in honour points; fair_play minus card points per 90 (pulled to the
-- position's mean); card_points and fair_play_minutes over the year's matches whose events are covered.
CREATE TABLE agg.player_award (
  season_id smallint NOT NULL REFERENCES core.seasons,
  player_id integer NOT NULL REFERENCES core.players,
  team_id integer REFERENCES core.teams,
  position text NOT NULL,             -- the level's main position
  universe text NOT NULL,
  eligible boolean NOT NULL,          -- the v8 ranking's: above the minutes bar
  linked boolean NOT NULL,            -- the v8 ranking's: a measured league
  top_division boolean NOT NULL,      -- the v8 ranking's: a club of a top division
  measured boolean NOT NULL,          -- false: a keeper without goals prevented on half his minutes in goal
  individual real NOT NULL,
  collective real NOT NULL,
  card_points integer NOT NULL,
  fair_play_minutes real NOT NULL,
  fair_play real NOT NULL,
  z_individual real NOT NULL,
  z_collective real NOT NULL,
  z_fair_play real NOT NULL,
  level real NOT NULL,
  score real NOT NULL,
  rank integer,                       -- NULL: out of the race, for `reason`
  reason text CHECK (reason IN ('minutes', 'league', 'not_top_division', 'keeper_data')),
  run_id integer NOT NULL REFERENCES agg.award_runs,
  PRIMARY KEY (season_id, player_id),
  CHECK ((rank IS NULL) = (reason IS NOT NULL))
);
CREATE INDEX player_award_rank ON agg.player_award(season_id, rank) WHERE rank IS NOT NULL;

-- One honour per player, team and edition, with what its value is read from: the values can be changed and the race
-- computed again from these rows alone (award.refresh), hence their double precision. Every league honour is kept,
-- whatever its rank.
CREATE TABLE agg.player_award_honours (
  season_id smallint NOT NULL REFERENCES core.seasons,
  player_id integer NOT NULL REFERENCES core.players,
  team_id integer NOT NULL REFERENCES core.teams,
  competition_season_id integer NOT NULL REFERENCES core.competition_seasons ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('league', 'national_cup', 'international')),
  reached text CHECK (reached IN ('round_of_16', 'quarter_final', 'semi_final', 'final', 'winner')),
  league_rank smallint,
  progress double precision,      -- a league's finished matches over its matches
  factor double precision,        -- the league factor (a league, a club's national cup); 1 for an international one
  prestige double precision,      -- an international competition's (power.PRESTIGE, CUP_PRESTIGE)
  share double precision NOT NULL,
  value double precision NOT NULL, -- share × the honour's value
  reason text CHECK (reason IN ('no_winner', 'no_league')),
  run_id integer NOT NULL REFERENCES agg.award_runs,
  PRIMARY KEY (season_id, player_id, competition_season_id, team_id)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON agg.award_runs, agg.player_award, agg.player_award_honours TO vega_calc;

-- Reads: every player's row (rank NULL out of the race) and his honours.
CREATE VIEW api.award_race AS
SELECT se.label AS season, a.season_id, a.player_id AS player_key, api.public_id('player', a.player_id) AS player_id, pl.name,
  ph.source_url AS image_url, api.public_id('team', a.team_id) AS team_id, t.name AS team, cr.source_url AS team_image_url,
  a.position, a.universe, a.eligible, a.linked, a.top_division, a.measured,
  a.individual::numeric::float8 AS individual, a.collective::numeric::float8 AS collective, a.card_points,
  a.fair_play_minutes::numeric::float8 AS fair_play_minutes, a.fair_play::numeric::float8 AS fair_play,
  a.z_individual::numeric::float8 AS z_individual, a.z_collective::numeric::float8 AS z_collective,
  a.z_fair_play::numeric::float8 AS z_fair_play, a.level::numeric::float8 AS level, a.score::numeric::float8 AS score,
  a.rank, a.reason, r.version, r.finished_at AS computed_at, r.reference_season
FROM agg.player_award a
JOIN core.seasons se ON se.id = a.season_id
JOIN core.players pl ON pl.id = a.player_id
LEFT JOIN core.assets ph ON ph.id = pl.photo_asset_id
LEFT JOIN core.teams t ON t.id = a.team_id
LEFT JOIN core.assets cr ON cr.id = t.crest_asset_id
JOIN agg.award_runs r ON r.id = a.run_id;

CREATE VIEW api.award_honours AS
SELECT h.season_id, h.player_id AS player_key, api.public_id('team', h.team_id) AS team_id, t.name AS team,
  coalesce(cs.cup_name, c.name) AS competition, h.kind, h.reached, h.league_rank, h.progress, h.factor, h.prestige, h.share, h.value,
  h.reason
FROM agg.player_award_honours h
JOIN core.teams t ON t.id = h.team_id
JOIN core.competition_seasons cs ON cs.id = h.competition_season_id
JOIN core.competitions c ON c.id = cs.competition_id;

GRANT SELECT ON api.award_race, api.award_honours TO vega_read;
