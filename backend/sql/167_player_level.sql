SET LOCAL lock_timeout = '3s';

-- One run per award year and computation: the version, the settings and the references it measured or read.
-- reference_season: the finished year whose player-matches gave `measured` (the year itself once it is over and
-- has levels: kept for the year after); NULL: the year's own rows, kept for no other year.
CREATE TABLE agg.level_runs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id smallint NOT NULL REFERENCES core.seasons,
  version text NOT NULL,
  status text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'published', 'superseded')),
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  players integer,
  reference_season smallint,
  settings jsonb NOT NULL,
  measured jsonb
);
CREATE UNIQUE INDEX level_runs_published ON agg.level_runs(season_id) WHERE status = 'published';

-- A player's sums of the award year at a position and a club: what the level of this year and half of the next
-- year's read. minutes: of the matches judged; per block, the minutes of the matches that measure it and the sum
-- of their values (an attacking position's centred on the year); for a keeper, goals prevented and their minutes.
CREATE TABLE agg.player_level_cells (
  season_id smallint NOT NULL REFERENCES core.seasons,
  player_id integer NOT NULL REFERENCES core.players,
  position text NOT NULL,
  team_id integer NOT NULL REFERENCES core.teams,
  minutes real NOT NULL,
  finishing_minutes real NOT NULL, creation_minutes real NOT NULL, progression_minutes real NOT NULL,
  defence_minutes real NOT NULL, retention_minutes real NOT NULL,
  finishing_sum real NOT NULL, creation_sum real NOT NULL, progression_sum real NOT NULL,
  defence_sum real NOT NULL, retention_sum real NOT NULL,
  keeper_minutes real NOT NULL, goals_prevented real NOT NULL,
  run_id integer NOT NULL REFERENCES agg.level_runs,
  PRIMARY KEY (season_id, player_id, position, team_id)
);

-- The level: level = own + club, own = blocks + starts (Elo points; 0 the ordinary player of the position).
CREATE TABLE agg.player_level (
  season_id smallint NOT NULL REFERENCES core.seasons,
  player_id integer NOT NULL REFERENCES core.players,
  position text NOT NULL,             -- the main one: most minutes over the two seasons, the season before for half
  team_id integer REFERENCES core.teams,
  universe text NOT NULL,
  eligible boolean NOT NULL,          -- the v8 ranking's: above the minutes bar
  linked boolean NOT NULL,            -- the v8 ranking's: a measured league
  minutes real NOT NULL,              -- of the year's club matches judged
  level real NOT NULL,
  own real NOT NULL,
  blocks real NOT NULL,
  starts real NOT NULL,
  club real NOT NULL,
  start_share real NOT NULL,
  club_level real NOT NULL,           -- the club's Elo above the mean, in units of 400
  score real NOT NULL,
  rank integer NOT NULL,              -- within the universe
  position_rank integer NOT NULL,
  run_id integer NOT NULL REFERENCES agg.level_runs,
  PRIMARY KEY (season_id, player_id)
);
CREATE INDEX player_level_rank ON agg.player_level(season_id, universe, rank);

-- Per position of the player: judged (acquired) with its share of the level, its value before centring, the level
-- he would have there alone and his talents per block in standard deviations; or not judged, with its minutes.
CREATE TABLE agg.player_level_positions (
  season_id smallint NOT NULL REFERENCES core.seasons,
  player_id integer NOT NULL REFERENCES core.players,
  position text NOT NULL,
  acquired boolean NOT NULL,
  minutes real NOT NULL,
  minutes_two_seasons real NOT NULL,
  share real,
  value real,
  level real,
  finishing real, creation real, progression real, defence real, retention real,
  run_id integer NOT NULL REFERENCES agg.level_runs,
  PRIMARY KEY (season_id, player_id, position)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON agg.level_runs, agg.player_level_cells, agg.player_level, agg.player_level_positions TO vega_calc;

-- Reads.
CREATE VIEW api.player_levels AS
SELECT se.label AS season, p.season_id, p.player_id AS player_key, api.public_id('player', p.player_id) AS player_id, pl.name,
  ph.source_url AS image_url, api.public_id('team', p.team_id) AS team_id, t.name AS team, cr.source_url AS team_image_url,
  p.position, p.universe, p.eligible, p.linked, p.minutes::numeric::float8 AS minutes,
  p.level::numeric::float8 AS level, p.own::numeric::float8 AS own, p.blocks::numeric::float8 AS blocks,
  p.starts::numeric::float8 AS starts, p.club::numeric::float8 AS club, p.start_share::numeric::float8 AS start_share,
  p.club_level::numeric::float8 AS club_level, p.score::numeric::float8 AS score, p.rank, p.position_rank,
  r.version, r.finished_at AS computed_at, r.reference_season
FROM agg.player_level p
JOIN core.seasons se ON se.id = p.season_id
JOIN core.players pl ON pl.id = p.player_id
LEFT JOIN core.assets ph ON ph.id = pl.photo_asset_id
LEFT JOIN core.teams t ON t.id = p.team_id
LEFT JOIN core.assets cr ON cr.id = t.crest_asset_id
JOIN agg.level_runs r ON r.id = p.run_id;

CREATE VIEW api.player_level_positions AS
SELECT p.season_id, p.player_id AS player_key, p.position, p.acquired, p.minutes::numeric::float8 AS minutes,
  p.minutes_two_seasons::numeric::float8 AS minutes_two_seasons, p.share::numeric::float8 AS share,
  p.value::numeric::float8 AS value, p.level::numeric::float8 AS level,
  p.finishing::numeric::float8 AS finishing, p.creation::numeric::float8 AS creation, p.progression::numeric::float8 AS progression,
  p.defence::numeric::float8 AS defence, p.retention::numeric::float8 AS retention
FROM agg.player_level_positions p;

GRANT SELECT ON api.player_levels, api.player_level_positions TO vega_read;
