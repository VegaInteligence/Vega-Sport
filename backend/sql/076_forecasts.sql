-- Match forecasts and season projections (vega/forecast.py): the model fitted on the
-- finished club matches from the two Elo strengths, the forecast of each match still to
-- play, and each domestic league replayed to its end.
CREATE TABLE agg.forecast_models (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version text NOT NULL,
  fitted_at timestamptz NOT NULL DEFAULT now(),
  matches integer NOT NULL,
  home_base real NOT NULL,
  home_slope real NOT NULL,
  away_base real NOT NULL,
  away_slope real NOT NULL,
  rho real NOT NULL,
  strength_spread real NOT NULL,
  simulations integer NOT NULL
);

CREATE TABLE agg.match_forecasts (
  match_id integer PRIMARY KEY,
  season_id smallint NOT NULL REFERENCES core.seasons,
  home_win real NOT NULL,
  draw real NOT NULL,
  away_win real NOT NULL,
  home_goals real NOT NULL,
  away_goals real NOT NULL,
  likely_home smallint NOT NULL,
  likely_away smallint NOT NULL,
  home_elo real NOT NULL,
  away_elo real NOT NULL,
  model_id integer NOT NULL REFERENCES agg.forecast_models
);
CREATE INDEX match_forecasts_season ON agg.match_forecasts(season_id);

CREATE TABLE agg.season_projections (
  competition_season_id integer NOT NULL REFERENCES core.competition_seasons ON DELETE CASCADE,
  team_id integer NOT NULL REFERENCES core.teams ON DELETE CASCADE,
  season_id smallint NOT NULL REFERENCES core.seasons,
  played smallint NOT NULL,
  points smallint NOT NULL,
  projected_points real NOT NULL,
  model_id integer NOT NULL REFERENCES agg.forecast_models,
  PRIMARY KEY (competition_season_id, team_id)
);
CREATE INDEX season_projections_season ON agg.season_projections(season_id);

-- The share of the replays a club finishes at each place; a place it never reaches has no row.
CREATE TABLE agg.season_projection_places (
  competition_season_id integer NOT NULL,
  team_id integer NOT NULL,
  place smallint NOT NULL CHECK (place >= 1),
  probability real NOT NULL CHECK (probability > 0 AND probability <= 1),
  PRIMARY KEY (competition_season_id, team_id, place),
  FOREIGN KEY (competition_season_id, team_id) REFERENCES agg.season_projections ON DELETE CASCADE
);
GRANT SELECT, INSERT, UPDATE, DELETE ON agg.forecast_models, agg.match_forecasts, agg.season_projections, agg.season_projection_places TO vega_calc;

CREATE VIEW api.match_forecasts AS
SELECT coalesce(k.provider_key, 'm_v' || lpad(f.match_id::text, 7, '0')) AS match_id, f.season_id,
  f.home_win::numeric::float8 AS home_win, f.draw::numeric::float8 AS draw, f.away_win::numeric::float8 AS away_win,
  f.home_goals::numeric::float8 AS home_goals, f.away_goals::numeric::float8 AS away_goals, f.likely_home, f.likely_away,
  o.version AS model_version, o.fitted_at, o.matches AS model_matches, f.match_id AS match_key
FROM agg.match_forecasts f
JOIN agg.forecast_models o ON o.id = f.model_id
LEFT JOIN core.provider_ids k ON k.entity_type = 'match' AND k.entity_id = f.match_id AND k.provider = 'pitchapi' AND k.is_current;

CREATE VIEW api.season_projections AS
SELECT p.competition_season_id, coalesce(tp.provider_key, 't_v' || lpad(p.team_id::text, 7, '0')) AS team_id, t.name,
  cr.source_url AS image_url, p.played, p.points, p.projected_points::numeric::float8 AS projected_points,
  o.version AS model_version, o.fitted_at, o.simulations, p.team_id AS team_key
FROM agg.season_projections p
JOIN core.teams t ON t.id = p.team_id
JOIN agg.forecast_models o ON o.id = p.model_id
LEFT JOIN core.assets cr ON cr.id = t.crest_asset_id
LEFT JOIN core.provider_ids tp ON tp.entity_type = 'team' AND tp.entity_id = p.team_id AND tp.provider = 'pitchapi' AND tp.is_current;

CREATE VIEW api.season_projection_places AS
SELECT s.competition_season_id, s.team_id AS team_key, s.place, s.probability::numeric::float8 AS probability
FROM agg.season_projection_places s;

GRANT SELECT ON api.match_forecasts, api.season_projections, api.season_projection_places TO vega_read;
