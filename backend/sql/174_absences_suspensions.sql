-- The injured and suspended players, lot 1 « Données » (VI-15; docs/calculs/09-audit-2026-11/FAILURE_MODES.md §59).
-- Additive: one table (the suspensions read from Transfermarkt's /player/{id}/absence), one more kind and one column on
-- the reader's queue, four views. The injuries (core.player_injuries, api.player_injuries) are not touched.
SET LOCAL lock_timeout = '3s';

-- A player's suspensions, a table of their own beside core.player_injuries rather than more rows of it: each unit
-- reconciles its own table (an episode the answer omits is marked absent_since, an empty answer is refused), so a read
-- of one can never mark or refuse because of the other's episodes; the competition and the possible games are facts of
-- a suspension only. Kept by (player, start, competition, label) and never deleted, as the injuries (160).
CREATE TABLE core.player_suspensions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id integer NOT NULL REFERENCES core.players,
  label text,
  start_date date NOT NULL,
  end_date date,
  days smallint,
  -- missedGamesCount and possibleMissingGamesCount as given: NULL is unknown, never zero.
  matches_missed smallint CHECK (matches_missed >= 0),
  matches_possible smallint CHECK (matches_possible >= 0),
  -- Transfermarkt's competition code as given (CL, FR1, EURO), and ours when the base already maps it
  -- (vega/sources/tm_history.LEAGUES): no mapping is invented.
  competition_code text CHECK (competition_code ~ '^[A-Za-z0-9]{1,12}$'),
  competition_id integer REFERENCES core.competitions ON DELETE SET NULL,
  season_year smallint,
  source core.provider NOT NULL,
  as_of date NOT NULL,
  absent_since date,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX player_suspensions_player ON core.player_suspensions (player_id, source);

-- The reader's queue: the suspensions unit, and the daily focus (vega/transfermarkt.py FOCUS_*): until when a unit of a
-- player who counts for a match close at hand is read again within a day (the kick-off of that match; NULL: not in focus).
ALTER TABLE ops.transfermarkt_reads DROP CONSTRAINT transfermarkt_reads_kind_check,
  ADD CONSTRAINT transfermarkt_reads_kind_check
    CHECK (kind IN ('profile', 'values', 'transfers', 'injuries', 'squad', 'club', 'search', 'suspensions')),
  ADD COLUMN focus_until timestamptz;
CREATE INDEX transfermarkt_reads_focus ON ops.transfermarkt_reads (focus_until, next_due_at) WHERE focus_until IS NOT NULL;

-- A player's suspensions as served: none of a doubted link.
CREATE VIEW api.player_suspensions AS
SELECT s.player_id AS player_key, api.public_id('player', s.player_id) AS player_id, 'suspension'::text AS kind, s.label,
  s.start_date, s.end_date, s.days, s.matches_missed, s.matches_possible, s.competition_code,
  CASE WHEN s.competition_id IS NOT NULL THEN api.public_id('competition', s.competition_id) END AS competition_id,
  c.name AS competition_name, s.season_year, s.absent_since
FROM core.player_suspensions s
LEFT JOIN core.competitions c ON c.id = s.competition_id
WHERE s.source = 'transfermarkt'
  AND NOT EXISTS (SELECT 1 FROM ops.provider_links l WHERE l.entity_type = 'player' AND l.provider = 'transfermarkt'
                  AND l.entity_id = s.player_id AND l.quarantined_at IS NOT NULL);

-- Whose suspensions were read (an accepted read: a 404 is a refusal, as for the injuries, 160).
CREATE VIEW api.player_suspension_reads AS
SELECT i.entity_id AS player_key, r.read_at
FROM core.provider_ids i
JOIN ops.transfermarkt_reads r ON r.kind = 'suspensions' AND r.provider_key = i.provider_key AND r.read_at IS NOT NULL
WHERE i.entity_type = 'player' AND i.provider = 'transfermarkt' AND i.is_current
  AND NOT EXISTS (SELECT 1 FROM ops.provider_links l WHERE l.entity_type = 'player' AND l.provider = 'transfermarkt'
                  AND l.provider_key = i.provider_key AND l.quarantined_at IS NOT NULL);

-- A club's current squad and what is known of each member's absences (GET /api/teams/{id}/absences). The squad: the
-- latest season of the linked club's Transfermarkt squad the base holds, its members not marked absent (the squads 118
-- shows for every linked club). A member is read when his injuries and his suspensions each have an accepted read of 45
-- days or less (a member not linked, doubted, never read or read too long ago is unknown, not available); read_on: the
-- older of his two reads.
CREATE VIEW api.team_absence_players AS
WITH settings AS (SELECT 45 AS fresh_days),
clubs AS (
  SELECT i.entity_id AS team_key, i.provider_key AS club_key,
    (SELECT max(q.season_year) FROM core.provider_squads q
     WHERE q.provider = 'transfermarkt' AND q.club_key = i.provider_key AND q.absent_since IS NULL) AS season_year
  FROM core.provider_ids i
  WHERE i.entity_type = 'team' AND i.provider = 'transfermarkt' AND i.is_current
    AND NOT EXISTS (SELECT 1 FROM ops.provider_links l WHERE l.entity_type = 'team' AND l.provider = 'transfermarkt'
                    AND l.provider_key = i.provider_key AND l.quarantined_at IS NOT NULL)
)
SELECT c.team_key, q.player_key AS provider_key, m.player_key, api.public_id('player', m.player_key) AS player_id, p.name,
  ph.source_url AS image_url, w.role, ri.read_at AS injuries_read_at, rs.read_at AS suspensions_read_at,
  (ri.read_at >= current_date - st.fresh_days AND rs.read_at >= current_date - st.fresh_days) IS TRUE AS is_read,
  CASE WHEN (ri.read_at >= current_date - st.fresh_days AND rs.read_at >= current_date - st.fresh_days) IS TRUE
       THEN least(ri.read_at, rs.read_at)::date END AS read_on
FROM clubs c
CROSS JOIN settings st
JOIN core.provider_squads q ON q.provider = 'transfermarkt' AND q.club_key = c.club_key AND q.season_year = c.season_year
  AND q.absent_since IS NULL
LEFT JOIN LATERAL (
  SELECT i.entity_id AS player_key FROM core.provider_ids i
  WHERE i.entity_type = 'player' AND i.provider = 'transfermarkt' AND i.provider_key = q.player_key AND i.is_current
    AND NOT EXISTS (SELECT 1 FROM ops.provider_links l WHERE l.entity_type = 'player' AND l.provider = 'transfermarkt'
                    AND l.provider_key = q.player_key AND l.quarantined_at IS NOT NULL)
) m ON true
LEFT JOIN core.players p ON p.id = m.player_key
LEFT JOIN core.assets ph ON ph.id = p.photo_asset_id
LEFT JOIN LATERAL (SELECT w.role FROM agg.player_power w WHERE w.player_id = m.player_key ORDER BY w.season_id DESC LIMIT 1) w ON true
LEFT JOIN ops.transfermarkt_reads ri ON m.player_key IS NOT NULL AND ri.kind = 'injuries' AND ri.provider_key = q.player_key
  AND ri.read_at IS NOT NULL
LEFT JOIN ops.transfermarkt_reads rs ON m.player_key IS NOT NULL AND rs.kind = 'suspensions' AND rs.provider_key = q.player_key
  AND rs.read_at IS NOT NULL;

-- The current absences of a club's current squad, one row per episode. Current: not marked absent_since, started today
-- at the latest, its end empty or today or later. An episode with an empty end is shown only while its unit's last
-- accepted read is 45 days old or less and, for an injury or an illness (or an unclassified episode), while the player
-- has played no match after its start; a suspension keeps only the first guard (it holds for one competition, he may
-- play in another). An episode with an end is bounded by it. readAt: the day of its unit's last accepted read.
CREATE VIEW api.team_absences AS
WITH settings AS (SELECT 45 AS fresh_days)
SELECT s.team_key, s.player_key, s.player_id, s.name, s.image_url, s.role, e.kind, e.label, e.start_date, e.end_date,
  e.matches_missed, e.matches_remaining, e.competition_code, e.competition_id, e.competition_name, e.read_on
FROM api.team_absence_players s
CROSS JOIN settings st
CROSS JOIN LATERAL (
  SELECT i.kind::text AS kind, i.label, i.start_date, i.end_date, i.matches_missed::integer AS matches_missed,
    NULL::integer AS matches_remaining, NULL::text AS competition_code, NULL::text AS competition_id, NULL::text AS competition_name,
    s.injuries_read_at::date AS read_on
  FROM core.player_injuries i
  WHERE i.player_id = s.player_key AND i.source = 'transfermarkt' AND s.injuries_read_at IS NOT NULL
    AND i.absent_since IS NULL AND i.start_date <= current_date
    AND (i.end_date >= current_date
         OR (i.end_date IS NULL AND s.injuries_read_at >= current_date - st.fresh_days
             AND NOT EXISTS (SELECT 1 FROM core.player_match_stats ms
                             JOIN core.matches mm ON mm.id = ms.match_id AND mm.season_id = ms.season_id
                             WHERE ms.player_id = s.player_key AND ms.season_id >= extract(year FROM i.start_date)::int - 1
                               AND ms.minutes_played > 0 AND mm.match_date > i.start_date)))
  UNION ALL
  SELECT 'suspension', u.label, u.start_date, u.end_date, u.matches_missed::integer,
    CASE WHEN u.matches_possible IS NOT NULL AND u.matches_missed IS NOT NULL THEN greatest(u.matches_possible - u.matches_missed, 0) END,
    u.competition_code,
    CASE WHEN u.competition_id IS NOT NULL THEN api.public_id('competition', u.competition_id) END,
    c.name, s.suspensions_read_at::date
  FROM core.player_suspensions u
  LEFT JOIN core.competitions c ON c.id = u.competition_id
  WHERE u.player_id = s.player_key AND u.source = 'transfermarkt' AND s.suspensions_read_at IS NOT NULL
    AND u.absent_since IS NULL AND u.start_date <= current_date
    AND (u.end_date >= current_date OR (u.end_date IS NULL AND s.suspensions_read_at >= current_date - st.fresh_days))
) e
WHERE s.player_key IS NOT NULL;

GRANT SELECT ON api.player_suspensions, api.player_suspension_reads, api.team_absence_players, api.team_absences TO vega_read;
