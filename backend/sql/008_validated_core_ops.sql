-- Align core and ops with the validated "Vega Sport — schéma v2" document (9 November 2026).
-- New enum values are added but never used by DDL here: the migration runner applies all
-- pending files in one transaction, and PostgreSQL forbids using a value added in it.

-- Sources of every fact the site shows today.
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'wikimedia';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'fifa';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'sportsapi';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'openligadb';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'international_results';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'football_data';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'espn';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'fixturedl';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'footballcsv';
ALTER TYPE core.provider ADD VALUE IF NOT EXISTS 'engsoccerdata';
ALTER TYPE core.asset_kind ADD VALUE IF NOT EXISTS 'venue_plan';
ALTER TYPE core.match_status ADD VALUE IF NOT EXISTS 'suspended';
ALTER TYPE ops.watch_state ADD VALUE IF NOT EXISTS 'stopped';
ALTER TYPE ops.resource_kind ADD VALUE IF NOT EXISTS 'catalog';
ALTER TYPE ops.resource_kind ADD VALUE IF NOT EXISTS 'ranking';
ALTER TYPE ops.resource_kind ADD VALUE IF NOT EXISTS 'archive_season';

-- A Vega season id is its starting year (2025 for 2025/2026); it orders the partitions.
ALTER TABLE core.seasons ALTER COLUMN id DROP IDENTITY;
ALTER TABLE core.seasons DROP COLUMN start_year;
ALTER TABLE core.seasons ADD CONSTRAINT seasons_id_is_start_year
  CHECK (id BETWEEN 1850 AND 2100 AND label = id::text || '/' || (id + 1)::text);

-- Names are not identities: two coaches, referees or stadiums can share one.
-- Identity goes through core.provider_ids (PitchAPI name key, Wikidata QID).
ALTER TABLE core.coaches DROP CONSTRAINT IF EXISTS coaches_name_key;
ALTER TABLE core.referees DROP CONSTRAINT IF EXISTS referees_name_key;
ALTER TABLE core.venues DROP CONSTRAINT IF EXISTS venues_name_key;

-- An entity keeps its former provider keys; one current key per provider.
ALTER TABLE core.provider_ids DROP CONSTRAINT IF EXISTS provider_ids_entity_type_entity_id_provider_key;
ALTER TABLE core.provider_ids ADD COLUMN is_current boolean NOT NULL DEFAULT true;
CREATE INDEX provider_ids_entity ON core.provider_ids(entity_type, entity_id);
CREATE UNIQUE INDEX provider_ids_current ON core.provider_ids(entity_type, entity_id, provider)
WHERE is_current;

ALTER TABLE core.assets
  ADD COLUMN author text,
  ADD COLUMN license text,
  ADD COLUMN source_page_url text;

ALTER TABLE core.teams
  ADD COLUMN founded_year smallint CHECK (founded_year BETWEEN 1800 AND 2100),
  ADD COLUMN home_venue_id integer REFERENCES core.venues;

ALTER TABLE core.coaches ADD COLUMN photo_asset_id integer REFERENCES core.assets;

ALTER TABLE core.venues
  ADD COLUMN commercial_name text,
  ADD COLUMN capacity integer CHECK (capacity >= 0),
  ADD COLUMN capacity_as_of date,
  ADD COLUMN latitude real CHECK (latitude BETWEEN -90 AND 90),
  ADD COLUMN longitude real CHECK (longitude BETWEEN -180 AND 180),
  ADD COLUMN opened_year smallint CHECK (opened_year BETWEEN 1800 AND 2100);

CREATE TABLE core.venue_plans(
  venue_id integer NOT NULL REFERENCES core.venues ON DELETE CASCADE,
  seq smallint NOT NULL CHECK (seq >= 0),
  title text NOT NULL,
  url text,
  image_asset_id integer REFERENCES core.assets,
  source text,
  format text,
  is_embedded boolean NOT NULL DEFAULT false,
  allow_geolocation boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (venue_id, seq),
  CHECK (url IS NOT NULL OR image_asset_id IS NOT NULL)
);

CREATE TYPE core.date_precision AS ENUM ('day', 'month', 'year');

CREATE TABLE core.team_coach_tenures(
  team_id integer NOT NULL REFERENCES core.teams,
  coach_id integer NOT NULL REFERENCES core.coaches,
  start_date date NOT NULL,
  end_date date,
  date_precision core.date_precision NOT NULL DEFAULT 'day',
  source core.provider NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (team_id, coach_id, start_date),
  CHECK (end_date IS NULL OR end_date >= start_date)
);
CREATE INDEX team_coach_tenures_current ON core.team_coach_tenures(team_id)
WHERE end_date IS NULL;

-- Rounds: league matchdays, cup rounds, group stages. Order is derived from kickoffs.
CREATE TYPE core.stage_kind AS ENUM ('regular', 'group', 'qualifying', 'playoff', 'knockout', 'final');

CREATE TABLE core.rounds(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competition_season_id integer NOT NULL REFERENCES core.competition_seasons,
  name text NOT NULL CHECK (btrim(name) <> ''),
  seq smallint CHECK (seq >= 0),
  stage core.stage_kind NOT NULL DEFAULT 'regular',
  is_two_legged boolean,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (competition_season_id, name)
);

ALTER TABLE core.matches
  DROP COLUMN round_name,
  ADD COLUMN round_id integer REFERENCES core.rounds,
  ADD COLUMN group_name text,
  ADD COLUMN leg smallint CHECK (leg IN (1, 2)),
  ADD COLUMN home_score_ht smallint CHECK (home_score_ht >= 0),
  ADD COLUMN away_score_ht smallint CHECK (away_score_ht >= 0),
  ADD COLUMN home_score_et smallint CHECK (home_score_et >= 0),
  ADD COLUMN away_score_et smallint CHECK (away_score_et >= 0),
  ADD COLUMN attendance integer CHECK (attendance >= 0),
  ADD COLUMN note text;
CREATE INDEX matches_round ON core.matches(round_id);

-- Promotion, relegation and European places of a league season.
CREATE TYPE core.zone_kind AS ENUM ('champions_league', 'europa_league', 'conference_league',
  'promotion', 'promotion_playoff', 'relegation_playoff', 'relegation');

CREATE TABLE core.competition_zones(
  competition_season_id integer NOT NULL REFERENCES core.competition_seasons,
  zone core.zone_kind NOT NULL,
  position_from smallint NOT NULL CHECK (position_from >= 1),
  position_to smallint NOT NULL,
  source core.provider NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (competition_season_id, zone),
  CHECK (position_to >= position_from)
);

-- Every spelling of an entity: official, short, alias ("cr7"), historical club names.
CREATE TYPE core.name_kind AS ENUM ('official', 'short', 'alias', 'historical', 'source_spelling');

CREATE TABLE core.entity_names(
  entity_type core.entity_type NOT NULL,
  entity_id integer NOT NULL,
  name text NOT NULL CHECK (btrim(name) <> ''),
  normalized text NOT NULL CHECK (normalized = lower(normalized) AND btrim(normalized) <> ''),
  kind core.name_kind NOT NULL,
  valid_from date,
  valid_to date,
  source core.provider NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (entity_type, entity_id, normalized),
  CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from)
);
CREATE INDEX entity_names_trgm ON core.entity_names USING gin(normalized gin_trgm_ops);

-- Official rankings: UEFA clubs and associations, FIFA, with SportsAPI as second provider.
CREATE TYPE core.ranking_kind AS ENUM ('uefa_clubs', 'uefa_associations', 'fifa_men');

CREATE TABLE core.ranking_editions(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind core.ranking_kind NOT NULL,
  provider core.provider NOT NULL,
  label text NOT NULL,
  period text,
  published_on date,
  is_current boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (kind, provider, label)
);

CREATE TABLE core.ranking_rows(
  edition_id integer NOT NULL REFERENCES core.ranking_editions ON DELETE CASCADE,
  row_no smallint NOT NULL CHECK (row_no >= 1),
  team_id integer REFERENCES core.teams,
  country_code text REFERENCES core.countries,
  position smallint CHECK (position >= 1),
  previous_position smallint CHECK (previous_position >= 1),
  points real,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (edition_id, row_no),
  UNIQUE (edition_id, team_id),
  CHECK ((team_id IS NULL) <> (country_code IS NULL))
);
CREATE INDEX ranking_rows_team ON core.ranking_rows(team_id);

CREATE TABLE core.ranking_row_seasons(
  edition_id integer NOT NULL,
  row_no smallint NOT NULL,
  season_id smallint NOT NULL REFERENCES core.seasons,
  points real,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (edition_id, row_no, season_id),
  FOREIGN KEY (edition_id, row_no) REFERENCES core.ranking_rows ON DELETE CASCADE
);

-- Observed standings keep each source apart; api.standings chooses one.
ALTER TABLE core.official_standings RENAME TO standings_official;
ALTER TABLE core.standings_official ALTER COLUMN as_of TYPE timestamptz;

-- Editorial lists of the home page, adjustable without a deploy.
CREATE TYPE core.list_kind AS ENUM ('featured_clubs', 'title_race_leagues', 'top_seven');

CREATE TABLE core.editorial_lists(
  list_kind core.list_kind NOT NULL,
  entity_type core.entity_type NOT NULL,
  entity_id integer NOT NULL,
  seq smallint NOT NULL CHECK (seq >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (list_kind, entity_id)
);

-- Scorers known only by name (archives, complementary sources).
ALTER TABLE core.match_events
  ADD COLUMN player_name text,
  ADD CONSTRAINT match_events_one_player_identity CHECK (player_id IS NULL OR player_name IS NULL);

CREATE INDEX shots_team ON core.shots(season_id, team_id);

-- Collection traceability: parser version and response fingerprint, never the response.
ALTER TABLE ops.fetch_log
  ADD COLUMN parser_version text,
  ADD COLUMN response_sha256 bytea CHECK (response_sha256 IS NULL OR octet_length(response_sha256) = 32),
  ADD COLUMN rows_written integer CHECK (rows_written >= 0),
  ADD COLUMN is_empty boolean;
ALTER TABLE ops.parse_failures ADD COLUMN parser_version text;

ALTER TABLE ops.resource_versions
  ADD COLUMN facts_revision bigint,
  ADD COLUMN published_at timestamptz;

CREATE TABLE ops.collection_progress(
  source core.provider NOT NULL,
  competition_season_id integer NOT NULL REFERENCES core.competition_seasons,
  family ops.fetch_family NOT NULL,
  expected integer NOT NULL DEFAULT 0 CHECK (expected >= 0),
  done integer NOT NULL DEFAULT 0 CHECK (done >= 0),
  empty integer NOT NULL DEFAULT 0 CHECK (empty >= 0),
  failed integer NOT NULL DEFAULT 0 CHECK (failed >= 0),
  last_success_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (source, competition_season_id, family)
);

CREATE TYPE ops.warning_kind AS ENUM ('score_disagreement', 'duplicate_match', 'unmatched_team', 'unmatched_player');

CREATE TABLE ops.data_warnings(
  match_id integer NOT NULL REFERENCES core.matches ON DELETE CASCADE,
  kind ops.warning_kind NOT NULL,
  detail text,
  detected_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (match_id, kind)
);
