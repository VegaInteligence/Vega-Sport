-- version club-indicators-v2).
--
-- 1. agg.team_season_stats gains the paired supports the calculator fills: for each ratio of
--    two statistics or two sides, its terms summed over the matches that know all of its inputs,
--    and the count of those matches (pair_<name>_n). Penalty attempts come from a match's
--    complete, reconciled shot set only, own goals from its goal events read in the order of
--    the score. The existing columns and their totals are unchanged.
-- 2. api.team_season keeps its 783 columns, their names, order and types (the baseline snapshot
--    backend/tests/fixtures/api_team_season_columns.json); its 503 table columns are listed by
--    name, so that the new ones follow the others. 13 of the 46 indicators read their paired
--    support: xg_per_shot, box_shots_pct, finishing_pm, keeper_pm, conversion_pct, field_tilt_pct, box_share_pct,
--    directness_pct, ppda_approx, def_actions_adj, duels_pct, aerials_pct, set_share_pct.
--    The other 33 are 012's expressions, unchanged. The pair_* columns are appended.
--    009, 012, 015 and api_schema.py are unchanged.
--    The view's text was written once, by a generator kept with the audit's evidence (outside the
--    repository), from that snapshot, api_schema._team_per_match() and club_indicators.py; it is
--    static from then on, like every migration. test_audit_club_aggregates.py checks its columns
--    against the snapshot and its indicators against the cohort percentiles'.
-- 3. The formula of each redefined indicator in agg.metric_definitions (a derived row, 015) is its
--    new expression.
--
-- Backfill: none in SQL. Until the calculator recomputes an edition (the ALL-SCOPE recompute of
-- docs/calculs/09-audit-2026-11/TRACEABILITY.md), its pair_* columns are NULL and the paired
-- indicators unavailable, never a value of the old definition.
