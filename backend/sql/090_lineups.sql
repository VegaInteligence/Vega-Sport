-- What a starting eleven changes to a match (vega/lineup.py): the Elo points one unit of
-- its outfield players' own rate is worth, fitted on the finished club matches; and the
-- reads behind "what if this player played in that one's place".
CREATE TABLE agg.lineup_models (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version text NOT NULL,
  fitted_at timestamptz NOT NULL DEFAULT now(),
  matches integer NOT NULL CHECK (matches > 0),
  -- The matches the Elo held at the fit: the model is fitted again when they have grown enough.
  rated integer NOT NULL CHECK (rated > 0),
  elo_per_unit real NOT NULL,
  elo_per_unit_error real NOT NULL CHECK (elo_per_unit_error > 0)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON agg.lineup_models TO vega_calc;

CREATE VIEW api.lineup_models AS
SELECT l.id, l.version, l.fitted_at, l.matches, l.elo_per_unit::numeric::float8 AS elo_per_unit,
  l.elo_per_unit_error::numeric::float8 AS elo_per_unit_error
FROM agg.lineup_models l;

-- A player's own part of a season in the ranking (his contributions without the level of
-- his club), with his minutes: what his own rate per 90 minutes is read from.
CREATE VIEW api.player_own_totals AS
SELECT p.season_id, p.player_id AS player_key, api.public_id('player', p.player_id) AS player_id, pl.name, p.role,
  p.team_id AS team_key, api.public_id('team', p.team_id) AS team_id, t.name AS team,
  p.minutes, p.own_total::numeric::float8 AS own_total
FROM agg.player_power p
JOIN core.players pl ON pl.id = p.player_id
LEFT JOIN core.teams t ON t.id = p.team_id;

-- A club's matches in a league (a competition the ranking gives a level to), one row per
-- match and side: the league a club plays the most in a season, and how many matches.
CREATE VIEW api.team_league_matches AS
SELECT m.season_id, m.home_team_id AS team_key, cs.competition_id AS competition_key, m.id AS match_key
FROM core.matches m
JOIN core.competition_seasons cs ON cs.id = m.competition_season_id AND cs.archive_key IS NULL AND cs.cup_key IS NULL
JOIN agg.league_levels l ON l.competition_id = cs.competition_id
UNION ALL
SELECT m.season_id, m.away_team_id, cs.competition_id, m.id
FROM core.matches m
JOIN core.competition_seasons cs ON cs.id = m.competition_season_id AND cs.archive_key IS NULL AND cs.cup_key IS NULL
JOIN agg.league_levels l ON l.competition_id = cs.competition_id;

GRANT SELECT ON api.lineup_models, api.player_own_totals, api.team_league_matches TO vega_read;
