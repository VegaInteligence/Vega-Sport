-- Win, draw and loss during a match (vega/inplay.py): the fitted model (the share of a
-- match's goals by quarter-hour and after the 90th minute, the red-card factors) and the
-- reads behind a match's minute-by-minute probabilities.
CREATE TABLE agg.inplay_models (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version text NOT NULL,
  fitted_at timestamptz NOT NULL DEFAULT now(),
  matches integer NOT NULL CHECK (matches > 0),
  goals integer NOT NULL CHECK (goals > 0),
  red_matches integer NOT NULL CHECK (red_matches >= 0),
  q1 double precision NOT NULL,
  q2 double precision NOT NULL,
  q3 double precision NOT NULL,
  q4 double precision NOT NULL,
  q5 double precision NOT NULL,
  q6 double precision NOT NULL,
  after_90 double precision NOT NULL,
  down double precision NOT NULL CHECK (down > 0),
  up double precision NOT NULL CHECK (up > 0)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON agg.inplay_models TO vega_calc;

CREATE VIEW api.inplay_models AS
SELECT m.id, m.version, m.fitted_at, m.matches, m.goals, m.red_matches, m.q1, m.q2, m.q3, m.q4, m.q5, m.q6, m.after_90, m.down, m.up
FROM agg.inplay_models m;

-- The forecast's coefficients (076), for the expected goals of a match already played.
CREATE VIEW api.forecast_models AS
SELECT f.id, f.version, f.fitted_at, f.matches, f.home_base::float8 AS home_base, f.home_slope::float8 AS home_slope,
  f.away_base::float8 AS away_base, f.away_slope::float8 AS away_slope, f.rho::float8 AS rho
FROM agg.forecast_models f;

-- A match's two strengths: the Elo each side entered it with, or, before the match is
-- rated, the Elo each side holds after its last rated match.
CREATE VIEW api.match_strengths AS
SELECT m.id AS match_key, m.season_id, m.status::text AS status, coalesce(m.is_neutral, false) AS neutral,
  m.home_score, m.away_score,
  coalesce(eh.elo_before, lh.elo_after)::float8 AS home_elo, coalesce(ea.elo_before, la.elo_after)::float8 AS away_elo
FROM core.matches m
LEFT JOIN agg.team_elo eh ON eh.match_id = m.id AND eh.team_id = m.home_team_id
LEFT JOIN agg.team_elo ea ON ea.match_id = m.id AND ea.team_id = m.away_team_id
LEFT JOIN LATERAL (SELECT e.elo_after FROM agg.team_elo e WHERE e.team_id = m.home_team_id AND eh.match_id IS NULL
                   ORDER BY e.kickoff_at DESC NULLS LAST LIMIT 1) lh ON true
LEFT JOIN LATERAL (SELECT e.elo_after FROM agg.team_elo e WHERE e.team_id = m.away_team_id AND ea.match_id IS NULL
                   ORDER BY e.kickoff_at DESC NULLS LAST LIMIT 1) la ON true;

-- A match's goals and dismissals in order, each with the side it counts for.
CREATE VIEW api.match_inplay_events AS
SELECT e.season_id, e.match_id AS match_key, e.seq, CASE e.event_type WHEN 'goal' THEN 'goal' ELSE 'red' END AS kind,
  e.minute, coalesce(e.minute_added, 0) AS minute_added,
  CASE WHEN e.team_id = m.home_team_id THEN 'home' WHEN e.team_id = m.away_team_id THEN 'away' END AS side
FROM core.match_events e
JOIN core.matches m ON m.id = e.match_id AND m.season_id = e.season_id
WHERE e.event_type IN ('goal', 'red_card') AND e.minute IS NOT NULL;

-- The last minute the source has measured of a match (its momentum), the clock of a match in progress.
CREATE VIEW api.match_clocks AS
SELECT x.season_id, x.match_id AS match_key, max(x.minute)::float8 AS minute
FROM core.match_momentum x
GROUP BY x.season_id, x.match_id;

GRANT SELECT ON api.inplay_models, api.forecast_models, api.match_strengths, api.match_inplay_events, api.match_clocks TO vega_read;
