-- Vega's own expected goals (vega/xg.py): the fitted model, one coefficient per term,
-- and the value it gives each shot; the match page reads it beside the source's xG.
CREATE TABLE agg.xg_models (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version text NOT NULL,
  fitted_at timestamptz NOT NULL DEFAULT now(),
  shots integer NOT NULL CHECK (shots > 0),
  goals integer NOT NULL CHECK (goals >= 0),
  penalty double precision CHECK (penalty >= 0 AND penalty <= 1),
  intercept double precision NOT NULL,
  angle double precision NOT NULL,
  distance double precision NOT NULL,
  distance_sq double precision NOT NULL,
  angle_distance double precision NOT NULL,
  header double precision NOT NULL,
  other_body double precision NOT NULL,
  from_corner double precision NOT NULL,
  set_piece double precision NOT NULL,
  fast_break double precision NOT NULL,
  free_kick double precision NOT NULL,
  throw_in double precision NOT NULL,
  individual_play double precision NOT NULL,
  header_distance double precision NOT NULL
);

CREATE TABLE agg.shot_xg (
  season_id smallint NOT NULL,
  match_id integer NOT NULL,
  shot_no smallint NOT NULL,
  xg real NOT NULL CHECK (xg >= 0 AND xg <= 1),
  model_id integer NOT NULL REFERENCES agg.xg_models,
  PRIMARY KEY (season_id, match_id, shot_no),
  FOREIGN KEY (match_id, season_id) REFERENCES core.matches(id, season_id) ON DELETE CASCADE
);
CREATE INDEX shot_xg_model ON agg.shot_xg(model_id);
GRANT SELECT, INSERT, UPDATE, DELETE ON agg.xg_models, agg.shot_xg TO vega_calc;

CREATE OR REPLACE VIEW api.match_shot_rows AS
SELECT s.season_id, s.match_id, s.shot_no, s.provider_shot_key AS id, s.period::text AS period, s.minute, s.minute_added,
  api.public_id('team', s.team_id) AS team_id,
  api.public_id('player', s.player_id) AS player_id, p.name AS player_name, pa.source_url AS player_image_url,
  api.public_id('player', s.keeper_id) AS keeper_id, k.name AS keeper_name, ka.source_url AS keeper_image_url,
  s.x, s.y, s.xg, s.xgot, s.is_on_target, s.goal_crossed_y, s.goal_crossed_z, s.is_inside_box,
  s.outcome::text AS outcome, s.situation::text AS situation, s.body_part::text AS body_part,
  s.is_blocked, s.blocked_x, s.blocked_y, s.is_own_goal, s.is_saved_off_line, v.xg AS vega_xg
FROM core.shots s
LEFT JOIN agg.shot_xg v ON v.season_id = s.season_id AND v.match_id = s.match_id AND v.shot_no = s.shot_no
LEFT JOIN core.players p ON p.id = s.player_id LEFT JOIN core.assets pa ON pa.id = p.photo_asset_id
LEFT JOIN core.players k ON k.id = s.keeper_id LEFT JOIN core.assets ka ON ka.id = k.photo_asset_id;
